#!/usr/bin/env python3
"""Convert base16 schemes (github.com/tinted-theming/schemes, MIT) into greyline
theme TOMLs.

The shipped palettes under worldtime/themes/ are generated by this script — run it
to refresh them, or to add any of the ~340 upstream schemes that greyline doesn't
bundle:

    git clone --depth 1 https://github.com/tinted-theming/schemes /tmp/schemes
    python tools/base16_to_theme.py --curated /tmp/schemes/base16 --out worldtime/themes
    python tools/base16_to_theme.py /tmp/schemes/base16/nord.yaml   # one, to stdout

A greyline theme is a map, not a text editor, so the base16 slots need translating
rather than copying — the mapping below is the whole design, and it was checked
against the hand-tuned 0.6.0 themes it replaces (it reproduces their colours to
within a shade):

    ocean       base00                      the sea / page background
    land        base01, or base02, or the two blended toward base03 — whichever
                first clears `_MIN_CONTRAST` against the ocean on the right side
                (lighter on dark schemes, darker on light): landmasses have to read
                as a distinct surface, and several schemes put base01 within a shade
                or two of base00, or below it
    border      base03                      country outlines
    grid_label  base04                      bottom-edge UTC-offset labels
    dot         base05                      city dots
    text        base06, or base05 where base06 cannot be read against the label
                plate (see `_text_slot`)    clock labels
    logo        base06                      tint for logo_invert
    idl         reddest accent              International Date Line
    gmt         greenest accent             UTC+0 column fill
    home        warmest accent (~amber),    home city dot + label
                or _ACCENT for schemes with a signature accent

Slots are picked by hue, not by base16's nominal "base08 = red" convention, because
schemes disagree: tokyo-night-dark's base08 is lavender and its red lives in base0F.

Polarity comes from the scheme's own `variant` field. The night side MULTIPLIES
toward `night`, so a dark scheme darkens base00 toward black at a low alpha, while a
light scheme needs a mid-tone (base03/base04 blended) and a much stronger alpha to
show a terminator at all. Everything else follows: strokes are halos *behind* text,
so they take the background's polarity, and grid/column tints flip white-on-dark to
black-on-light.
"""

